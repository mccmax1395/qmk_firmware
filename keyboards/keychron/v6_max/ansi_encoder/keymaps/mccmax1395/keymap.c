// clang-format on
bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    if (!process_record_keychron_common(keycode, record)) {
        return false;
    }

    switch (keycode) {
        case UPDIR:  // Types ../ to go up a directory on the shell.
        if (record->event.pressed) {
            SEND_STRING(" cd ../" SS_TAP(X_ENTER));
        }
        case VALUE:
         if (record->event.pressed) {
            SEND_STRING("?????");
        }
        return false;
    }
    return true;
    
}


static void blackout_numpad_when_numlock_off(uint8_t led_min, uint8_t led_max) {
    // Clamp to the chunk QMK is currently updating (led_min..led_max-1)
    // and set the requested LEDs to off.
    struct { uint8_t start; uint8_t end; } ranges[] = {
        {37, 40},
        {58, 60},
        {74, 77},
        {91, 93},
        {105, 107},
    };

    for (uint8_t r = 0; r < (sizeof(ranges) / sizeof(ranges[0])); r++) {
        uint8_t start = ranges[r].start;
        uint8_t end   = ranges[r].end;

        if (start < led_min) start = led_min;
        if (end >= led_max)  end = led_max - 1;

        if (start > end) continue;

        for (uint8_t i = start; i <= end; i++) {
            rgb_matrix_set_color(i, 0, 0, 0); // off
        }
    }
}


static void set_override_range(uint8_t led_min, uint8_t led_max, uint8_t r, uint8_t g, uint8_t b) {
    uint8_t start = OVERRIDE_START;
    uint8_t end   = OVERRIDE_END;

    if (start < led_min) start = led_min;
    if (end >= led_max)  end = led_max - 1;

    for (uint8_t i = start; i <= end; i++) {
        rgb_matrix_set_color(i, r, g, b);
    }
}

bool rgb_matrix_indicators_advanced_user(uint8_t led_min, uint8_t led_max) {
    uint8_t layer = get_highest_layer(layer_state | default_layer_state);

    // Caps lock: override EVERYTHING to red
    if (host_keyboard_led_state().caps_lock) {
        for (uint8_t i = led_min; i < led_max; i++) {
            rgb_matrix_set_color(i, RGB_RED);
        }
        return false;
    }

    // Layer 1: solid blue everywhere
    if (layer == 1) {
        for (uint8_t i = led_min; i < led_max; i++) {
            rgb_matrix_set_color(i, RGB_BLUE);
        }
        return false;
    }

    // Layer 3: solid yellow everywhere
    if (layer == 3) {
        for (uint8_t i = led_min; i < led_max; i++) {
            rgb_matrix_set_color(i, RGB_YELLOW);
        }
        return false;
    }

    // Layer 0 / 2: keep base RGB effect, override only LEDs 16-19
    if (layer == 0) {
        set_override_range(led_min, led_max, 0, 0, 255);      // blue
    } else if (layer == 2) {
        set_override_range(led_min, led_max, 255, 255, 0);    // yellow
    }

    if (!host_keyboard_led_state().caps_lock && !host_keyboard_led_state().num_lock) {
    blackout_numpad_when_numlock_off(led_min, led_max);
}
    return false;
}